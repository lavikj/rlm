"""
Evaluate RLM's question-answering performance using the VCS QA dataset.

This script:
1. Loads the VCS QA dataset (generated by build_dataset_vcs.py)
2. Loads VCS documentation as context
3. Uses RLM to answer questions from the dataset
4. Uses an LLM to evaluate answer quality against golden answers
5. Generates evaluation metrics and report
"""

import json
import os
import sys
import time
from pathlib import Path
from typing import Any

from dotenv import load_dotenv

# Ensure repo root is importable
REPO_ROOT = Path(__file__).resolve().parents[1]
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from rlm import RLM
from rlm.clients.openai import OpenAIClient


def load_vcs_documentation(markdown_file: str) -> list[str]:
    """
    Load VCS documentation as a list of document chunks.

    We split the large document into manageable chunks so the RLM can
    iterate over them without exceeding context limits.

    Args:
        markdown_file: Path to the VCS markdown file

    Returns:
        List of document chunk strings
    """
    with open(markdown_file, encoding="utf-8") as f:
        content = f.read()

    # Split into chunks by major sections (## headers)
    chunks = []
    current_chunk = []
    current_size = 0
    max_chunk_size = 50000  # ~50k chars per chunk

    for line in content.split("\n"):
        current_chunk.append(line)
        current_size += len(line)

        # Split on major headers or when chunk gets too large
        if (line.startswith("## ") and current_size > 10000) or current_size > max_chunk_size:
            chunk_text = "\n".join(current_chunk)
            if chunk_text.strip():
                chunks.append(chunk_text)
            current_chunk = []
            current_size = 0

    # Don't forget the last chunk
    if current_chunk:
        chunk_text = "\n".join(current_chunk)
        if chunk_text.strip():
            chunks.append(chunk_text)

    return chunks


def evaluate_answer(
    evaluator_client: OpenAIClient,
    question: str,
    generated_answer: str,
    golden_answer: str,
) -> tuple[float, str]:
    """
    Use an LLM to evaluate how well the generated answer matches the golden answer.

    Args:
        evaluator_client: LLM client for evaluation
        question: The question being answered
        generated_answer: Answer generated by RLM
        golden_answer: Ground truth answer

    Returns:
        Tuple of (score between 0-1, explanation)
    """
    prompt = f"""You are evaluating a question-answering system's response quality.

Question: {question}

Golden Answer (Ground Truth):
{golden_answer}

Generated Answer:
{generated_answer}

Evaluate how well the generated answer addresses the question compared to the golden answer.

Criteria:
- Correctness: Does it contain the key information from the golden answer?
- Completeness: Is it missing any important points?
- Accuracy: Is the information factually correct?
- Relevance: Does it directly address the question?

Provide:
1. A score from 0.0 to 1.0 (where 1.0 = perfect match, 0.0 = completely wrong)
2. A brief explanation (1-2 sentences)

Output format (JSON):
{{
  "score": <float between 0.0 and 1.0>,
  "explanation": "<brief explanation>"
}}

Output only the JSON, nothing else."""

    response = evaluator_client.completion(prompt)

    # Parse JSON response
    try:
        if "```json" in response:
            response = response.split("```json")[1].split("```")[0].strip()
        elif "```" in response:
            response = response.split("```")[1].split("```")[0].strip()

        result = json.loads(response)
        return float(result["score"]), result["explanation"]
    except Exception as e:
        print(f"Error parsing evaluation response: {e}")
        print(f"Response was: {response}")
        return -1.0, "Error parsing evaluation"


def run_evaluation(
    dataset_file: str,
    markdown_file: str,
    backend: str,
    backend_kwargs: dict,
    evaluator_client: OpenAIClient,
    output_file: str,
    max_questions: int | None = None,
) -> dict[str, Any]:
    """
    Run the complete evaluation pipeline.

    Args:
        dataset_file: Path to the VCS QA dataset JSON file
        markdown_file: Path to the VCS markdown documentation
        backend: Backend name for RLM
        backend_kwargs: Kwargs for the backend client
        evaluator_client: LLM client for evaluation
        output_file: Path to save detailed results
        max_questions: Maximum number of questions to evaluate (None = all)

    Returns:
        Dictionary with evaluation metrics
    """
    # Load dataset
    with open(dataset_file, encoding="utf-8") as f:
        dataset = json.load(f)

    if max_questions:
        dataset = dataset[:max_questions]

    print(f"Loaded {len(dataset)} QA pairs for evaluation")

    # Load documentation as context
    print("Loading VCS documentation context...")
    documentation = load_vcs_documentation(markdown_file)
    total_chars = sum(len(d) for d in documentation)
    print(f"Loaded {len(documentation)} document chunks ({total_chars:,} characters total)")

    # Initialize RLM
    rlm = RLM(backend=backend, backend_kwargs=backend_kwargs, verbose=True)

    # Run evaluation
    results = []
    scores = []

    # Resume logic
    if os.path.exists(output_file):
        try:
            with open(output_file, encoding="utf-8") as f:
                existing_data = json.load(f)
                if "results" in existing_data and isinstance(existing_data["results"], list):
                    results = existing_data["results"]
                    scores = [r["score"] for r in results if "score" in r and r["score"] >= 0]
                    print(f"\nResuming from question {len(results) + 1}...")
        except Exception as e:
            print(f"\nWarning: Could not resume from {output_file}: {e}")

    print("\nStarting evaluation...")
    print("=" * 60)

    try:
        from rich.progress import (
            BarColumn,
            Progress,
            SpinnerColumn,
            TextColumn,
            TimeRemainingColumn,
        )

        use_rich = True
    except ImportError:
        use_rich = False

    if use_rich:
        with Progress(
            SpinnerColumn(),
            TextColumn("[progress.description]{task.description}"),
            BarColumn(),
            TextColumn("[progress.percentage]{task.percentage:>3.0f}%"),
            TimeRemainingColumn(),
        ) as progress:
            task = progress.add_task(
                "[cyan]Evaluating...", total=len(dataset), completed=len(results)
            )

            for i in range(len(results), len(dataset)):
                qa_pair = dataset[i]
                progress.update(task, description=f"[cyan]Q{i + 1}: {qa_pair['question'][:50]}...")

                result = _evaluate_single_question(
                    rlm, evaluator_client, qa_pair, documentation, i
                )
                results.append(result)
                if result["score"] >= 0:
                    scores.append(result["score"])

                # Save intermediate results
                _save_intermediate_results(results, scores, dataset, output_file)
                progress.advance(task)
    else:
        for i in range(len(results), len(dataset)):
            qa_pair = dataset[i]
            print(f"\n[{i + 1}/{len(dataset)}] {qa_pair['question'][:60]}...")

            result = _evaluate_single_question(rlm, evaluator_client, qa_pair, documentation, i)
            results.append(result)
            if result["score"] >= 0:
                scores.append(result["score"])

            # Save intermediate results
            _save_intermediate_results(results, scores, dataset, output_file)

    # Final metrics
    metrics = _compute_metrics(scores, len(dataset))

    # Save final results
    output = {"metrics": metrics, "results": results}
    with open(output_file, "w", encoding="utf-8") as f:
        json.dump(output, f, indent=2, ensure_ascii=False)

    # Print summary
    print("\n" + "=" * 60)
    print("EVALUATION COMPLETE")
    print("=" * 60)
    print(f"Total Questions: {metrics['total_questions']}")
    print(f"Average Score: {metrics['average_score']:.3f}")
    print(f"High Quality (>= 0.8): {metrics['high_quality_percentage']:.1f}%")
    print(f"Acceptable (>= 0.6): {metrics['acceptable_percentage']:.1f}%")
    print("\nScore Distribution:")
    for category, count in metrics["score_distribution"].items():
        print(f"  {category}: {count}")
    print(f"\nDetailed results saved to: {output_file}")
    print("=" * 60)

    return metrics


def _evaluate_single_question(
    rlm: RLM,
    evaluator_client: OpenAIClient,
    qa_pair: dict,
    documentation: list[str],
    index: int,
) -> dict:
    """Evaluate a single question and return the result dict."""
    rlm_prompt = f"""You are answering questions about VCS (Synopsys Verilog Compiler Simulator) documentation.

Use the provided documentation context to answer the following question accurately and concisely.

Question: {qa_pair['question']}

Context available: VCS User Guide technical documentation

Please provide a clear, accurate answer based on the documentation."""

    start_time = time.time()
    try:
        rlm_response = rlm.completion(prompt=documentation, root_prompt=rlm_prompt)
        generated_answer = rlm_response.response
        generation_time = time.time() - start_time
    except Exception as e:
        generated_answer = f"ERROR: {str(e)}"
        generation_time = 0.0

    # Evaluate answer quality
    try:
        score, explanation = evaluate_answer(
            evaluator_client,
            qa_pair["question"],
            generated_answer,
            qa_pair["answer"],
        )
    except Exception as e:
        score = -1.0
        explanation = f"Evaluation error: {str(e)}"

    return {
        "id": qa_pair["id"],
        "source_file": qa_pair.get("source_file", "unknown"),
        "question": qa_pair["question"],
        "golden_answer": qa_pair["answer"],
        "generated_answer": generated_answer,
        "score": score,
        "explanation": explanation,
        "generation_time": generation_time,
    }


def _save_intermediate_results(
    results: list[dict], scores: list[float], dataset: list, output_file: str
):
    """Save intermediate results to file."""
    metrics = _compute_metrics(scores, len(dataset), len(results))
    output = {"metrics": metrics, "results": results}
    with open(output_file, "w", encoding="utf-8") as f:
        json.dump(output, f, indent=2, ensure_ascii=False)


def _compute_metrics(
    scores: list[float], total_questions: int, questions_processed: int | None = None
) -> dict:
    """Compute evaluation metrics from scores."""
    if questions_processed is None:
        questions_processed = len(scores)

    avg_score = sum(scores) / len(scores) if scores else 0.0
    high_quality = sum(1 for s in scores if s >= 0.8) / len(scores) if scores else 0.0
    acceptable = sum(1 for s in scores if s >= 0.6) / len(scores) if scores else 0.0

    return {
        "total_questions": total_questions,
        "questions_processed": questions_processed,
        "average_score": avg_score,
        "high_quality_percentage": high_quality * 100,
        "acceptable_percentage": acceptable * 100,
        "score_distribution": {
            "excellent (>= 0.9)": sum(1 for s in scores if s >= 0.9),
            "good (0.8-0.9)": sum(1 for s in scores if 0.8 <= s < 0.9),
            "acceptable (0.6-0.8)": sum(1 for s in scores if 0.6 <= s < 0.8),
            "poor (< 0.6)": sum(1 for s in scores if s < 0.6),
        },
    }


def main():
    """Main execution function."""
    load_dotenv()

    # Paths
    qa_dir = Path(__file__).resolve().parent
    repo_root = qa_dir.parent

    DATASET_FILE = str(qa_dir / "vcs_qa_dataset_valid.json")
    MARKDOWN_FILE = str(
        repo_root / "example-docs/Synopsys/VCS/VCS User Guide 2019.06-SP1/markdown.md"
    )
    OUTPUT_FILE = str(qa_dir / "vcs_evaluation_results_qwen_big.json")
    MAX_QUESTIONS = None  # Set to a number to limit evaluation, None = all

    # Check for API key
    api_key = os.getenv("OPENROUTER_API_KEY") or os.getenv("OPENAI_API_KEY")
    if not api_key:
        raise ValueError(
            "OPENROUTER_API_KEY or OPENAI_API_KEY environment variable not set."
        )

    # Configure RLM backend
    backend = "openrouter" if os.getenv("OPENROUTER_API_KEY") else "openai"
    rlm_model = os.getenv("RLM_MODEL", "qwen/qwen3-235b-a22b-2507")
    openrouter_provider = os.getenv("OPENROUTER_PROVIDER", "Cerebras")

    backend_kwargs: dict[str, Any] = {"model_name": rlm_model}
    if backend == "openrouter":
        backend_kwargs["extra_body"] = {
            "provider": {"order": [openrouter_provider], "allow_fallbacks": False}
        }

    # Configure evaluator
    eval_model = os.getenv("EVAL_MODEL", "google/gemini-3-flash-preview")
    eval_base_url = os.getenv("EVAL_BASE_URL", "https://openrouter.ai/api/v1")
    evaluator_client = OpenAIClient(model_name=eval_model, base_url=eval_base_url)

    print("VCS RLM Question-Answering Evaluation")
    print("=" * 60)
    print(f"Dataset: {DATASET_FILE}")
    print(f"Documentation: {MARKDOWN_FILE}")
    print(f"RLM Backend: {backend}")
    print(f"RLM Model: {backend_kwargs['model_name']}")
    print(f"Evaluator Model: {evaluator_client.model_name}")
    print(f"Output: {OUTPUT_FILE}")
    print("=" * 60)

    # Run evaluation
    run_evaluation(
        dataset_file=DATASET_FILE,
        markdown_file=MARKDOWN_FILE,
        backend=backend,
        backend_kwargs=backend_kwargs,
        evaluator_client=evaluator_client,
        output_file=OUTPUT_FILE,
        max_questions=MAX_QUESTIONS,
    )


if __name__ == "__main__":
    main()
